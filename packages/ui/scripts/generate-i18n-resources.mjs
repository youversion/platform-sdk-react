#!/usr/bin/env node
/**
 * Generates packages/ui/src/i18n/resources.generated.ts and slim catalogs
 * that drop unused locale keys. Source files under locales/ stay complete.
 *
 * Usage:
 *   node scripts/generate-i18n-resources.mjs          # one-shot (build / CI)
 *   node scripts/generate-i18n-resources.mjs --watch   # watch locale dir in dev
 */
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  unlinkSync,
  watch,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(scriptDir, '..');
const uiSrcDir = join(uiRoot, 'src');
const localesDir = join(uiSrcDir, 'i18n/locales');
const slimDir = join(uiSrcDir, 'i18n/slim');
const outputPath = join(uiSrcDir, 'i18n/resources.generated.ts');
const providerStringsPath = join(uiSrcDir, 'i18n/provider-strings.generated.ts');
const PROVIDER_STRING_KEYS = ['errorHeading', 'invalidAppKeyError'];
const T_CALL_RE = /\bt\(\s*['"]([^'"]+)['"]/g;
const I18N_KEY_RE = /i18nKey\s*=\s*['"]([^'"]+)['"]/g;

const defaultNS = 'translation';
const watchMode = process.argv.includes('--watch');

/** Quote object keys only when the locale is not a valid JS identifier (e.g. pt-BR). */
function formatLocaleKey(locale) {
  if (/^[A-Za-z_$][\w$]*$/.test(locale)) {
    return locale;
  }
  // Match Prettier singleQuote so generate:i18n output stays commit-stable.
  return `'${locale.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** One locale per line so Prettier does not reflow the generated file. */
function formatLocaleTuple(locales) {
  return `[\n${locales.map((locale) => `  '${locale.replace(/'/g, "\\'")}',`).join('\n')}\n]`;
}

function generateI18nResources() {
  const localeFiles = readdirSync(localesDir).filter((file) => file.endsWith('.json'));

  if (!localeFiles.includes('en.json')) {
    console.error('generate-i18n-resources: en.json is required in packages/ui/src/i18n/locales/');
    process.exit(1);
  }

  const locales = localeFiles
    .map((file) => file.replace(/\.json$/, ''))
    .sort((a, b) => {
      if (a === 'en') return -1;
      if (b === 'en') return 1;
      return a.localeCompare(b);
    });

  const lazyLocales = locales.filter((locale) => locale !== 'en');
  const usedKeys = collectUsedCatalogKeys();
  mkdirSync(slimDir, { recursive: true });
  for (const locale of locales) {
    const catalog = JSON.parse(readFileSync(join(localesDir, `${locale}.json`), 'utf8'));
    const slim = Object.fromEntries(
      Object.entries(catalog).filter(([key]) => usedKeys.has(key)),
    );
    writeGeneratedFile(join(slimDir, `${locale}.json`), `${JSON.stringify(slim)}\n`);
  }
  const loaderEntries = lazyLocales
    .map(
      (locale) =>
        `  ${formatLocaleKey(locale)}: (): Promise<LocaleJsonModule> => import('./slim/${locale}.json'),`,
    )
    .join('\n');

  const content = `// AUTO-GENERATED by generate-i18n-resources.mjs — do not edit

import en from './slim/en.json' with { type: 'json' };

const defaultNS = '${defaultNS}';

type LocaleJsonModule = { default: Record<string, string> };

export const resources = {
  en: { [defaultNS]: en },
} as const;

export const supportedLngs = ${formatLocaleTuple(locales)} as const;

export const localeLoaders = {
${loaderEntries}
};
`;

  writeGeneratedFile(outputPath, content);
  writeGeneratedFile(providerStringsPath, generateProviderStrings(locales));
  console.log(`Generated ${outputPath} (${locales.length} locales: ${locales.join(', ')})`);
}

function collectUsedCatalogKeys() {
  const used = new Set(PROVIDER_STRING_KEYS);
  const queue = [uiSrcDir];
  while (queue.length > 0) {
    const dir = queue.pop();
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const fullPath = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === 'locales' || entry.name === 'slim') continue;
        queue.push(fullPath);
        continue;
      }
      if (!/\.(?:[cm]?[jt]sx?)$/.test(entry.name)) continue;
      if (entry.name.includes('.generated.')) continue;
      if (/\.(?:test|stories)\./.test(entry.name)) continue;
      const source = readFileSync(fullPath, 'utf8');
      for (const pattern of [T_CALL_RE, I18N_KEY_RE]) {
        pattern.lastIndex = 0;
        let match = pattern.exec(source);
        while (match) {
          used.add(match[1]);
          match = pattern.exec(source);
        }
      }
    }
  }
  return used;
}

function generateProviderStrings(locales) {
  const entries = locales
    .map((locale) => {
      const catalog = JSON.parse(readFileSync(join(localesDir, `${locale}.json`), 'utf8'));
      const fields = PROVIDER_STRING_KEYS.map((key) => {
        const value = catalog[key];
        if (typeof value !== 'string') {
          throw new Error(`generate-i18n-resources: ${locale}.json is missing string key "${key}"`);
        }
        return `    ${key}: ${JSON.stringify(value)},`;
      }).join('\n');
      return `  ${formatLocaleKey(locale)}: {\n${fields}\n  },`;
    })
    .join('\n');
  return `// AUTO-GENERATED by generate-i18n-resources.mjs — do not edit

export const providerStrings = {
${entries}
} as const;

export const providerStringLngs = ${formatLocaleTuple(locales)} as const;
`;
}

/**
 * Replace resources.generated.ts without truncating it in place.
 *
 * CI runs UI typecheck and UI build in parallel; both call this generator.
 * writeFileSync empties the destination first, so tsc can read a zero-length
 * module and fail with TS2305 (no exported member 'resources' / 'supportedLngs').
 * Skip the write when content is unchanged so parallel no-op runs do not race.
 */
function writeGeneratedFile(destination, content) {
  try {
    if (readFileSync(destination, 'utf8') === content) {
      return;
    }
  } catch {
    // Missing or unreadable — write a fresh copy.
  }

  const tempPath = `${destination}.${process.pid}.tmp`;
  writeFileSync(tempPath, content, 'utf8');
  try {
    renameSync(tempPath, destination);
  } catch (error) {
    try {
      unlinkSync(tempPath);
    } catch {
      // Best-effort cleanup; the rename error is the one to surface.
    }
    throw error;
  }
}

function shouldRegenerate(filename) {
  // macOS directory watches often omit filename; regenerate to stay safe.
  if (filename == null) {
    return true;
  }
  return filename.endsWith('.json');
}

function startWatch() {
  generateI18nResources();

  let debounceTimer;
  const debounceMs = 75;

  const scheduleRegenerate = (filename) => {
    if (!shouldRegenerate(filename)) {
      return;
    }

    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      try {
        generateI18nResources();
      } catch (error) {
        console.error('generate-i18n-resources: watch regenerate failed:', error);
      }
    }, debounceMs);
  };

  const watcher = watch(localesDir, (eventType, filename) => {
    scheduleRegenerate(filename);
  });

  watcher.on('error', (error) => {
    console.error('generate-i18n-resources: watch error:', error);
    process.exit(1);
  });

  console.log(`Watching ${localesDir} for locale JSON changes…`);
}

if (watchMode) {
  startWatch();
} else {
  generateI18nResources();
}
