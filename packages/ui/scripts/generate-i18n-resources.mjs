#!/usr/bin/env node
/**
 * Generates packages/ui/src/i18n/resources.generated.ts from locale JSON files.
 *
 * Usage:
 *   node scripts/generate-i18n-resources.mjs          # one-shot (build / CI)
 *   node scripts/generate-i18n-resources.mjs --watch   # watch locale dir in dev
 */
import { readFileSync, readdirSync, renameSync, unlinkSync, watch, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(scriptDir, '..');
const localesDir = join(uiRoot, 'src/i18n/locales');
const outputPath = join(uiRoot, 'src/i18n/resources.generated.ts');

const defaultNS = 'translation';
const watchMode = process.argv.includes('--watch');

/** Quote object keys only when the locale is not a valid JS identifier (e.g. pt-BR). */
function formatLocaleKey(locale) {
  if (/^[A-Za-z_$][\w$]*$/.test(locale)) {
    return locale;
  }
  // Match Prettier singleQuote so generate:i18n output stays commit-stable.
  return `'${locale.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function generateI18nResources() {
  const localeFiles = readdirSync(localesDir).filter((file) => file.endsWith('.json'));

  if (!localeFiles.includes('en.json')) {
    console.error('generate-i18n-resources: en.json is required in packages/ui/src/i18n/locales/');
    process.exit(1);
  }

  const locales = localeFiles
    .map((file) => file.replace(/\.json$/, ''))
    .sort((a, b) => {
      if (a === 'en') return -1;
      if (b === 'en') return 1;
      return a.localeCompare(b);
    });

  const imports = locales
    .map(
      (locale, index) =>
        `import locale${index} from './locales/${locale}.json' with { type: 'json' };`,
    )
    .join('\n');

  const resourceEntries = locales
    .map(
      (locale, index) =>
        `  ${formatLocaleKey(locale)}: { [defaultNS]: locale${index} },`,
    )
    .join('\n');

  const content = `// AUTO-GENERATED by generate-i18n-resources.mjs — do not edit

${imports}

const defaultNS = '${defaultNS}';

export const resources = {
${resourceEntries}
} as const;

export const supportedLngs = Object.keys(resources);
`;

  writeGeneratedFile(content);
  console.log(`Generated ${outputPath} (${locales.length} locales: ${locales.join(', ')})`);
}

/**
 * Replace resources.generated.ts without truncating it in place.
 *
 * CI runs UI typecheck and UI build in parallel; both call this generator.
 * writeFileSync empties the destination first, so tsc can read a zero-length
 * module and fail with TS2305 (no exported member 'resources' / 'supportedLngs').
 * Skip the write when content is unchanged so parallel no-op runs do not race.
 */
function writeGeneratedFile(content) {
  try {
    if (readFileSync(outputPath, 'utf8') === content) {
      return;
    }
  } catch {
    // Missing or unreadable — write a fresh copy.
  }

  const tempPath = `${outputPath}.${process.pid}.tmp`;
  writeFileSync(tempPath, content, 'utf8');
  try {
    renameSync(tempPath, outputPath);
  } catch (error) {
    try {
      unlinkSync(tempPath);
    } catch {
      // Best-effort cleanup; the rename error is the one to surface.
    }
    throw error;
  }
}

function shouldRegenerate(filename) {
  // macOS directory watches often omit filename; regenerate to stay safe.
  if (filename == null) {
    return true;
  }
  return filename.endsWith('.json');
}

function startWatch() {
  generateI18nResources();

  let debounceTimer;
  const debounceMs = 75;

  const scheduleRegenerate = (filename) => {
    if (!shouldRegenerate(filename)) {
      return;
    }

    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      try {
        generateI18nResources();
      } catch (error) {
        console.error('generate-i18n-resources: watch regenerate failed:', error);
      }
    }, debounceMs);
  };

  const watcher = watch(localesDir, (eventType, filename) => {
    scheduleRegenerate(filename);
  });

  watcher.on('error', (error) => {
    console.error('generate-i18n-resources: watch error:', error);
    process.exit(1);
  });

  console.log(`Watching ${localesDir} for locale JSON changes…`);
}

if (watchMode) {
  startWatch();
} else {
  generateI18nResources();
}
